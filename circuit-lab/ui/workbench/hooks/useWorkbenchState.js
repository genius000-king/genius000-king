import {useRef, useState} from 'react';
import {readMode} from '../../../engines/performance/index.js';
import {blankState, debugHook, load, loadIssue} from '../storage.js';

/** Every piece of workbench state and every ref, in one place. Also exposes the test hook. */
export function useWorkbenchState() {
  const [project, setProject] = useState(load),
    [selected, setSelected] = useState([]),
    [wireId, setWireId] = useState(null),
    [mode, setMode] = useState('select'),
    [library, setLibrary] = useState(false),
    [pinInfo, setPinInfo] = useState(null),
    [cameraTools, setCameraTools] = useState(false),
    [more, setMore] = useState(false),
    [query, setQuery] = useState(''),
    [category, setCategory] = useState('All'),
    [sim, setSim] = useState(blankState),
    [backend, setBackend] = useState('Starting renderer'),
    [toast, setToast] = useState(''),
    [error, setError] = useState(null),
    [compiled, setCompiled] = useState(false),
    [hover, setHover] = useState(null),
    [pending, setPending] = useState(null),
    [drawer, setDrawer] = useState(null),
    [docs, setDocs] = useState(false),
    [menu, setMenu] = useState(false),
    [connect, setConnect] = useState(false),
    [editingWire, setEditingWire] = useState(null),
    [pair, setPair] = useState(['', '']),
    [inspectorTab, setInspectorTab] = useState('properties'),
    [split, setSplit] = useState(project.editor?.split ?? 43),
    [dock, setDock] = useState(project.editor?.dock ?? 'left'),
    [panel, setPanel] = useState(project.editor?.panel ?? {x: 0, y: 0}),
    [minimized, setMinimized] = useState(false),
    [glass, setGlass] = useState(project.editor?.glass ?? 0.66),
    [serialInput, setSerialInput] = useState(''),
    [audioEnabled, setAudioEnabled] = useState(false),
    [grid, setGrid] = useState(true),
    [saveState, setSaveState] = useState('Saved locally'),
    [historyVersion, setHistoryVersion] = useState(0),
    [graphicsGeneration, setGraphicsGeneration] = useState(0),
    [performanceMode, setPerformanceMode] = useState(readMode),
    [resolution, setResolution] = useState(null),
    [newFile, setNewFile] = useState(false),
    [fileName, setFileName] = useState('helpers.ino'),
    [gallery, setGallery] = useState(false),
    [tools, setTools] = useState(false),
    [full, setFull] = useState(false),
    [build, setBuild] = useState(null); // memory report of the last compile
  const sceneRoot = useRef(null),
    scene = useRef(null),
    worker = useRef(null),
    current = useRef(project),
    simRef = useRef(sim),
    history = useRef({undo: [], redo: []}),
    callbacks = useRef({}),
    handStart = useRef(null),
    initial = useRef(project),
    importRef = useRef(null),
    notifyTimer = useRef(),
    audio = useRef(null),
    editorPanel = useRef(null),
    didCamera = useRef(false),
    preserveBadSave = useRef(!!loadIssue.message),
    serialBottom = useRef(null),
    runSource = useRef(''),
    latest = useRef({});
  current.current = project;
  simRef.current = sim;
  latest.current = {selected, wireId, mode, pending};
  if (process.env.NODE_ENV !== 'production' || debugHook)
    window.__circuitLab = {
      project: () => current.current,
      state: () => simRef.current,
      scene: () => scene.current,
    };
  return {
    build,
    setBuild,
    project,
    setProject,
    selected,
    setSelected,
    wireId,
    setWireId,
    mode,
    setMode,
    library,
    setLibrary,
    pinInfo,
    setPinInfo,
    cameraTools,
    setCameraTools,
    more,
    setMore,
    query,
    setQuery,
    category,
    setCategory,
    sim,
    setSim,
    backend,
    setBackend,
    toast,
    setToast,
    error,
    setError,
    compiled,
    setCompiled,
    hover,
    setHover,
    pending,
    setPending,
    drawer,
    setDrawer,
    docs,
    setDocs,
    menu,
    setMenu,
    connect,
    setConnect,
    editingWire,
    setEditingWire,
    pair,
    setPair,
    inspectorTab,
    setInspectorTab,
    split,
    setSplit,
    dock,
    setDock,
    panel,
    setPanel,
    minimized,
    setMinimized,
    glass,
    setGlass,
    serialInput,
    setSerialInput,
    audioEnabled,
    setAudioEnabled,
    grid,
    setGrid,
    saveState,
    setSaveState,
    historyVersion,
    setHistoryVersion,
    graphicsGeneration,
    setGraphicsGeneration,
    performanceMode,
    setPerformanceMode,
    resolution,
    setResolution,
    newFile,
    setNewFile,
    fileName,
    setFileName,
    gallery,
    setGallery,
    tools,
    setTools,
    full,
    setFull,
    sceneRoot,
    scene,
    worker,
    current,
    simRef,
    history,
    callbacks,
    handStart,
    initial,
    importRef,
    notifyTimer,
    audio,
    editorPanel,
    didCamera,
    preserveBadSave,
    serialBottom,
    runSource,
    latest,
  };
}
